"""ISRO SIH Quantitative Evaluation Metrics Engine.

Provides standalone, offline-compatible implementations of mandatory evaluation
metrics specified in ISRO_SIH_SPEC.md for sovereign remote-sensing benchmarks:
1. BLEU-4: Bilingual Evaluation Understudy (4-gram) with smoothing for VQA & captioning.
2. ROUGE-L: Longest Common Subsequence (Precision, Recall, F1) for scene descriptions.
3. CIDEr: Consensus-based Image Description Evaluation (TF-IDF weighted n-gram consensus).
4. mIoU: Mean Intersection over Union across semantic segmentation / change masks.

These functions are strictly decoupled from FastAPI / HTTP runtime contexts and
can be invoked directly by CLI evaluation runners, training scripts, or test harnesses.
"""

from __future__ import annotations

import math
import re
from collections import Counter
from typing import Any, Dict, List, Sequence, Union

import numpy as np
from nltk.translate.bleu_score import SmoothingFunction, sentence_bleu
from rouge_score import rouge_scorer


def _tokenize(text: str) -> List[str]:
    """Offline-safe regex word tokenization preserving alphanumerics.
    
    Avoids hard dependency on external NLTK punkt data downloads in air-gapped environments.
    """
    return re.findall(r"\b\w+\b", str(text).lower())


def calculate_bleu4(reference: str, hypothesis: str) -> float:
    """Calculates smoothed sentence-level BLEU-4 score between reference and hypothesis texts.

    Uses Chen and Cherry (2014) Smoothing Method 4 to prevent zero scores on short
    remote-sensing captions where high-order n-gram overlaps may be sparse.

    Args:
        reference: Ground-truth reference caption or answer string.
        hypothesis: Predicted candidate caption or answer string generated by model.

    Returns:
        float: BLEU-4 score scaled in [0.0, 1.0].
    """
    ref_tokens = _tokenize(reference)
    hyp_tokens = _tokenize(hypothesis)

    if not ref_tokens and not hyp_tokens:
        return 1.0
    if not ref_tokens or not hyp_tokens:
        return 0.0

    smooth = SmoothingFunction().method4
    # Weights for BLEU-4: uniform 25% distribution across 1-gram to 4-gram
    weights = (0.25, 0.25, 0.25, 0.25)

    try:
        score = sentence_bleu(
            references=[ref_tokens],
            hypothesis=hyp_tokens,
            weights=weights,
            smoothing_function=smooth,
        )
        return float(max(0.0, min(1.0, score)))
    except Exception:
        return 0.0


def calculate_rouge_l(reference: str, hypothesis: str) -> Dict[str, float]:
    """Calculates ROUGE-L (Longest Common Subsequence) precision, recall, and F-measure.

    Evaluates structural sentence overlap and word ordering for remote-sensing
    captioning and multi-turn visual question answering.

    Args:
        reference: Ground-truth reference string.
        hypothesis: Predicted candidate string from vision-language assistant.

    Returns:
        dict[str, float]: Dictionary containing:
            - "precision": Proportion of LCS in candidate text.
            - "recall": Proportion of LCS in reference text.
            - "fmeasure": Harmonic mean of precision and recall (ROUGE-L F1).
    """
    ref_str = str(reference).strip()
    hyp_str = str(hypothesis).strip()

    if not ref_str and not hyp_str:
        return {"precision": 1.0, "recall": 1.0, "fmeasure": 1.0}
    if not ref_str or not hyp_str:
        return {"precision": 0.0, "recall": 0.0, "fmeasure": 0.0}

    scorer = rouge_scorer.RougeScorer(["rougeL"], use_stemmer=True)
    score_dict = scorer.score(ref_str, hyp_str)
    rouge_l_score = score_dict["rougeL"]

    return {
        "precision": float(rouge_l_score.precision),
        "recall": float(rouge_l_score.recall),
        "fmeasure": float(rouge_l_score.fmeasure),
    }


def calculate_cider(
    references: Union[List[str], Sequence[str], str],
    hypothesis: str,
) -> float:
    """Calculates CIDEr (Consensus-based Image Description Evaluation) score.

    Implements the CIDEr-D formulation (Vedaldi et al., CVPR 2015) using TF-IDF
    weighted n-gram consensus across 1-to-4 grams with length-penalty clipping.
    Measures consensus between candidate caption and one or more reference captions.

    Args:
        references: One or more ground-truth reference captions.
        hypothesis: Model-generated candidate caption.

    Returns:
        float: CIDEr score scaled conventionally in [0.0, 10.0].
    """
    if isinstance(references, str):
        ref_list = [references]
    else:
        ref_list = [str(r) for r in references if str(r).strip()]

    hyp_str = str(hypothesis).strip()
    if not ref_list or not hyp_str:
        return 0.0

    hyp_tokens = _tokenize(hyp_str)
    ref_tokens_list = [_tokenize(r) for r in ref_list if _tokenize(r)]

    if not hyp_tokens or not ref_tokens_list:
        return 0.0

    def _get_ngrams(tokens: List[str], n: int) -> List[tuple[str, ...]]:
        return [tuple(tokens[i : i + n]) for i in range(len(tokens) - n + 1)]

    all_docs = [hyp_tokens] + ref_tokens_list
    total_docs = len(all_docs)

    ngram_scores: List[float] = []

    for n in range(1, 5):
        hyp_ngrams = _get_ngrams(hyp_tokens, n)
        if not hyp_ngrams:
            ngram_scores.append(0.0)
            continue

        hyp_counts = Counter(hyp_ngrams)
        hyp_total = float(sum(hyp_counts.values()))

        # Document frequencies across the reference collection
        df: Counter[tuple[str, ...]] = Counter()
        for doc in all_docs:
            for ng in set(_get_ngrams(doc, n)):
                df[ng] += 1

        # TF-IDF vector for hypothesis
        hyp_vec: Dict[tuple[str, ...], float] = {}
        for ng, count in hyp_counts.items():
            idf = math.log(max(1.0, (total_docs + 1.0) / (df[ng] + 1.0))) + 1.0
            hyp_vec[ng] = (count / hyp_total) * idf

        hyp_norm = math.sqrt(sum(v**2 for v in hyp_vec.values()))
        if hyp_norm < 1e-12:
            ngram_scores.append(0.0)
            continue

        ref_similarities: List[float] = []
        for r_tokens in ref_tokens_list:
            r_ngrams = _get_ngrams(r_tokens, n)
            if not r_ngrams:
                ref_similarities.append(0.0)
                continue

            r_counts = Counter(r_ngrams)
            r_total = float(sum(r_counts.values()))

            r_vec: Dict[tuple[str, ...], float] = {}
            for ng, count in r_counts.items():
                idf = math.log(max(1.0, (total_docs + 1.0) / (df[ng] + 1.0))) + 1.0
                r_vec[ng] = (count / r_total) * idf

            r_norm = math.sqrt(sum(v**2 for v in r_vec.values()))
            if r_norm < 1e-12:
                ref_similarities.append(0.0)
                continue

            # Cosine similarity
            dot = sum(hyp_vec.get(ng, 0.0) * r_vec.get(ng, 0.0) for ng in hyp_vec)
            sim = dot / (hyp_norm * r_norm)

            # CIDEr-D Gaussian length penalty (sigma = 6.0)
            len_diff = len(hyp_tokens) - len(r_tokens)
            penalty = math.exp(-(len_diff**2) / (2.0 * (6.0**2)))

            ref_similarities.append(float(sim * penalty))

        if ref_similarities:
            ngram_scores.append(float(sum(ref_similarities) / len(ref_similarities)))
        else:
            ngram_scores.append(0.0)

    # Standard CIDEr-D: equal weighting across n=1..4 scaled by factor of 10.0
    cider_score = (sum(ngram_scores) / 4.0) * 10.0
    return float(max(0.0, cider_score))


def calculate_miou(
    pred_mask: np.ndarray,
    true_mask: np.ndarray,
    num_classes: int = 2,
) -> float:
    """Calculates Mean Intersection over Union (mIoU) across semantic segmentation classes.

    Flattens spatial mask tensors, computes class-wise Jaccard indices (IoU), and
    returns the unweighted macro-average across active classes:

        mIoU = (1 / |C_active|) * sum_{c in C_active} (I_c / U_c)

    Gracefully handles continuous probability maps by applying 0.5 decision thresholds,
    and handles zero-union edge cases (classes absent from both ground truth and predictions).

    Args:
        pred_mask: Predicted segmentation mask array (discrete class labels or probability map).
        true_mask: Ground-truth reference mask array.
        num_classes: Number of discrete semantic categories (default 2 for binary change/water).

    Returns:
        float: Mean Intersection over Union score scaled in [0.0, 1.0].

    Raises:
        ValueError: If pred_mask and true_mask element counts do not match.
    """
    pred_arr = np.asarray(pred_mask)
    true_arr = np.asarray(true_mask)

    if pred_arr.size != true_arr.size:
        raise ValueError(
            f"Dimension mismatch: pred_mask elements ({pred_arr.size}) != true_mask elements ({true_arr.size})"
        )

    # Threshold float probability arrays for binary segmentation tasks
    if np.issubdtype(pred_arr.dtype, np.floating) and num_classes == 2:
        pred_flat = (pred_arr > 0.5).astype(np.int64).flatten()
    else:
        pred_flat = pred_arr.astype(np.int64).flatten()

    if np.issubdtype(true_arr.dtype, np.floating) and num_classes == 2:
        true_flat = (true_arr > 0.5).astype(np.int64).flatten()
    else:
        true_flat = true_arr.astype(np.int64).flatten()

    ious: List[float] = []

    for c in range(num_classes):
        intersection = np.logical_and(pred_flat == c, true_flat == c).sum()
        union = np.logical_or(pred_flat == c, true_flat == c).sum()

        if union == 0:
            # Class absent from both ground-truth and hypothesis masks
            continue

        iou_c = float(intersection) / float(union)
        ious.append(iou_c)

    if not ious:
        # If all classes had zero union, masks are identical empty sets
        return 1.0 if np.array_equal(pred_flat, true_flat) else 0.0

    return float(np.mean(ious))
